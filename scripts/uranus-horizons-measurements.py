#!/usr/bin/env python3
"""The #633 Uranus system study: what the committed Horizons responses say
about Uranus and its five major moons as an observer sees them.

Deterministic: reads only docs/studies/uranus-system/horizons/*.txt (each
verified against the body digest in its own header) and prints Markdown on
stdout. Nothing is typed from memory; every number is a row of a fixture.
"""
import hashlib
import re
import sys
from pathlib import Path

DIR = Path(__file__).parent.parent / "docs/studies/uranus-system/horizons"


def table(name):
    raw = (DIR / f"{name}.txt").read_text(encoding="utf-8")
    head, body = raw.split("\n", 6)[:6], raw.split("\n", 6)[6]
    digest = re.search(r"# body-sha256: ([0-9a-f]+)", raw).group(1)
    if hashlib.sha256(body.encode("utf-8")).hexdigest() != digest:
        sys.exit(f"{name}: the body does not match its recorded digest")
    lines = body.splitlines()
    soe = lines.index("$$SOE")
    eoe = lines.index("$$EOE")
    header = next(l for l in reversed(lines[:soe]) if l.lstrip().startswith("Date__"))
    names = [h.strip() for h in header.split(",")]
    names[1], names[2] = "sun", "moon"
    rows = []
    for line in lines[soe + 1:eoe]:
        cells = [c.strip() for c in line.split(",")]
        rows.append(dict(zip(names, cells)))
    return rows


def num(row, key):
    v = row.get(key, "")
    try:
        return float(v)
    except ValueError:
        return None


def extreme(rows, key, fn):
    vals = [(num(r, key), r["Date__(UT)__HR:MN:SS"]) for r in rows if num(r, key) is not None]
    return fn(vals)


def out(line=""):
    print(line)


def main():
    out("# Uranus system study (#633): what the Horizons responses say")
    out()
    out("Generated by `scripts/uranus-horizons-measurements.py` from the committed responses in"
        " `horizons/`, each verified against its recorded body digest. Horizons answers Uranus"
        " and its moons from its own satellite solution and the Earth from DE441.")
    out()
    uranus = table("matrix-7d-uranus-oslo")
    out("## Uranus, every 7 days 1900-2100, from Oslo")
    out()
    out(f"{len(uranus):,} rows.")
    out()
    out("| quantity | least | at (UT) | greatest | at (UT) |")
    out("|---|---:|---|---:|---|")
    for key, label in (("Ang-diam", "equatorial diameter (″)"), ("delta", "distance (AU)"),
                       ("S-T-O", "phase angle (°)"), ("Illu%", "illuminated (%)"),
                       ("ObsSub-LAT", "sub-observer latitude (°, planetodetic)"),
                       ("NP.ang", "north pole position angle (°)")):
        lo = extreme(uranus, key, min)
        hi = extreme(uranus, key, max)
        out(f"| {label} | {lo[0]:g} | {lo[1]} | {hi[0]:g} | {hi[1]} |")
    mag = table("magnitudes-30d-uranus-geocentric")
    lo, hi = extreme(mag, "APmag", min), extreme(mag, "APmag", max)
    out(f"| apparent magnitude, geocentric, 30-day | {lo[0]:g} | {lo[1]} | {hi[0]:g} | {hi[1]} |")
    out()
    out("## The almanac oppositions, hourly from Oslo")
    out()
    out("Each window runs three days either side of the almanac's hour. The row at that hour is"
        " shown, and the window's closest row, marked *edge* where it is the window's first or"
        " last row (the true closest approach then lies outside the window).")
    out()
    out("| window | rows | at the almanac hour (UT) | distance (AU) | diameter (″) | phase angle (°) |"
        " closest in the window (UT) | distance (AU) |")
    out("|---|---:|---|---:|---:|---:|---|---:|")
    for path in sorted(DIR.glob("*-uranus-oslo-hourly.txt")):
        rows = table(path.stem)
        mid = rows[len(rows) // 2]
        k = min(range(len(rows)), key=lambda i: num(rows[i], "delta"))
        edge = " (edge)" if k in (0, len(rows) - 1) else ""
        out(f"| {path.stem} | {len(rows)} | {mid['Date__(UT)__HR:MN:SS']} | {num(mid, 'delta'):.6f}"
            f" | {num(mid, 'Ang-diam'):.3f} | {num(mid, 'S-T-O'):.4f}"
            f" | {rows[k]['Date__(UT)__HR:MN:SS']}{edge} | {num(rows[k], 'delta'):.6f} |")
    out()
    for moon in ("miranda", "ariel", "umbriel", "titania", "oberon"):
        rows = table(f"matrix-7d-{moon}-oslo")
        out(f"## {moon.capitalize()}, every 7 days 2000-2100, from Oslo")
        out()
        out(f"{len(rows):,} rows.")
        out()
        lo, hi = extreme(rows, "ang-sep", min), extreme(rows, "ang-sep", max)
        out(f"- **Separation from Uranus's centre**: {lo[0]:g}″ ({lo[1]}) to {hi[0]:g}″ ({hi[1]}).")
        lo, hi = extreme(rows, "Ang-diam", min), extreme(rows, "Ang-diam", max)
        out(f"- **Angular diameter**: {lo[0]:g}″ to {hi[0]:g}″.")
        mag = table(f"magnitudes-30d-{moon}-geocentric")
        lo, hi = extreme(mag, "APmag", min), extreme(mag, "APmag", max)
        out(f"- **Apparent magnitude, geocentric, 30-day**: {lo[0]:g} ({lo[1]}) to {hi[0]:g} ({hi[1]}).")
        counts = {}
        for r in rows:
            counts[r.get("vis.", "")] = counts.get(r.get("vis.", ""), 0) + 1
        out("- **Horizons' visibility codes over the rows**: "
            + ", ".join(f"`{k or ' '}` {v:,}" for k, v in sorted(counts.items())) + ".")
        out()
        out(f"### {moon.capitalize()} at the oppositions, every 10 minutes, geocentric")
        out()
        out("| window | rows | greatest separation (″) | at (UT) | least separation (″) | visibility codes |")
        out("|---|---:|---:|---|---:|---|")
        for path in sorted(DIR.glob(f"opposition-*-{moon}-geocentric-10m.txt")):
            w = table(path.stem)
            hi, lo = extreme(w, "ang-sep", max), extreme(w, "ang-sep", min)
            c = {}
            for r in w:
                c[r.get("vis.", "")] = c.get(r.get("vis.", ""), 0) + 1
            out(f"| {path.stem} | {len(w)} | {hi[0]:g} | {hi[1]} | {lo[0]:g} | "
                + ", ".join(f"`{k or ' '}` {v}" for k, v in sorted(c.items())) + " |")
        out()


if __name__ == "__main__":
    main()
