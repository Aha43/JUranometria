    /** One family's symbol on a square of the chart's paper. */
    static BufferedImage swatch(Family family, int sizePx, int boxPx) {
        BufferedImage image = new BufferedImage(boxPx, boxPx,
                BufferedImage.TYPE_INT_RGB);
        Graphics2D g = image.createGraphics();
        try {
            g.setColor(Color.WHITE);
            g.fillRect(0, 0, boxPx, boxPx);
            g.setRenderingHint(RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);
            ChartRenderer.drawLegendSymbol(g, typeFor(family),
                    boxPx / 2.0, boxPx / 2.0, sizePx);
        } finally {
            g.dispose();
        }
        return image;
    }

    /** A catalogue type that draws this family's symbol. */
    public static DsoType typeFor(Family family) {
        for (DsoType type : DsoType.values()) {
            if (ChartRenderer.symbolForType(type) == family.symbol()) {
                return type;
            }
        }
        throw new IllegalStateException("no type draws " + family.symbol());
    }

    /** The share of inked pixels two swatches do not share. */
    static double difference(BufferedImage a, BufferedImage b) {
        int differing = 0;
        int inked = 0;
        for (int y = 0; y < a.getHeight(); y++) {
            for (int x = 0; x < a.getWidth(); x++) {
                boolean inkA = isInk(a, x, y);
                boolean inkB = isInk(b, x, y);
                if (inkA || inkB) {
                    inked++;
                    if (inkA != inkB) {
                        differing++;
                    }
                }
            }
        }
        return inked == 0 ? 0.0 : 100.0 * differing / inked;
    }

    private static boolean isInk(BufferedImage image, int x, int y) {
        return (image.getRGB(x, y) & 0xff) < 250;
    }

    /** The bounding box of everything a swatch drew. */
    static java.awt.Rectangle inkBounds(BufferedImage image) {
        int minX = image.getWidth();
        int minY = image.getHeight();
        int maxX = -1;
        int maxY = -1;
        for (int y = 0; y < image.getHeight(); y++) {
            for (int x = 0; x < image.getWidth(); x++) {
                if (isInk(image, x, y)) {
                    minX = Math.min(minX, x);
                    minY = Math.min(minY, y);
                    maxX = Math.max(maxX, x);
                    maxY = Math.max(maxY, y);
                }
            }
        }
        return maxX < 0 ? new java.awt.Rectangle(0, 0, 0, 0)
                : new java.awt.Rectangle(minX, minY, maxX - minX + 1,
                        maxY - minY + 1);
    }

