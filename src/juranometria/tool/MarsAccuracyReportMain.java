package juranometria.tool;

import java.io.IOException;

import juranometria.solar.MarsService;

/**
 * The Mars service's accuracy against JPL Horizons and Espenak's named
 * events, as a kept report (issue #602): every quantity's worst
 * difference by era beside the target ruled on #601, the moons' states
 * against Horizons' codes, and the published oppositions and
 * conjunctions. Deterministic: the service and the fixtures are fixed,
 * the numbers rounded. Written to
 * {@code docs/studies/mars-system/service-accuracy.md} by
 * {@code make mars-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class MarsAccuracyReportMain {

    private MarsAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        MarsService service = MarsService.load();
        MarsComparison.Result result = new MarsComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Mars service against Horizons and Espenak (#602)\n\n")
                .append("Generated by `juranometria.tool.MarsAccuracyReportMain`")
                .append(" (`make mars-accuracy-report`) from the service over the bundled Solar System,")
                .append(" planets and Mars System packs and the Horizons responses committed under")
                .append(" `horizons/`; `MarsReferenceVectorTest` and `MarsNamedEventsTest` hold these")
                .append(" numbers to the targets ruled on #601. Observers at sea level, UT1 = UTC, the")
                .append(" atlas's own time scales, the Sun's deflection in every apparent place, the phase")
                .append(" angle held to Horizons' `phi` (M-4), the pole with its periodic terms (M-3).")
                .append(" Mars answers from ").append(service.firstDay()).append(" to ")
                .append(service.lastDay()).append("; Phobos and Deimos from ")
                .append(MarsService.MOONS_FIRST_DAY).append(" up to, not including, 2050-01-01 00:00 TDB.\n\n")
                .append(MarsComparison.report(result));
        System.out.print(out);
    }
}
