    private static void journey(AllSkyCases.Case c, AllSkyComposition.Services services,
                                SkyPosition chartCentre) throws Exception {
        p("## 11. From the whole sky into an ordinary chart");
        p("");
        Observer observer = AllSkyCases.oslo(c.instant());
        AllSkyCases finder = new AllSkyCases(services);
        Map<String, AllSkyCases.Seen> seen = finder.bodies(observer);
        double central = AllSkyMeridian.midheaven(AllSkyOrientation.ECLIPTIC, observer);
        AllSkyMap map = new AllSkyMap(AllSkyForm.HAMMER, AllSkyOrientation.ECLIPTIC, central);
        AllSkyProjection projection = new AllSkyProjection(map);
        AllSkyComposition.Ask ask = new AllSkyComposition.Ask(observer, ChartPalette.WHITE_PAPER,
                AllSkyStudyWords.in("en"), LIMIT, true, true, MONITOR_W, MONITOR_H);
        String target = !seen.get("saturn").belowHorizon() ? "saturn" : "jovian.jupiter";
        Object[] result = new Object[4];
        SwingUtilities.invokeAndWait(() -> {
            try {
                AllSkyComposition.Page page = AllSkyComposition.paint(projection, ask, services);
                Projections.drawnForStudy(projection, () -> {
                    ReferenceInk.BodyPlacement b = page.chart().renderedBodies().stream()
                            .filter(x -> x.identity().equals(target)).findFirst().orElseThrow();
                    var hit = page.chart().selectableBodyAt(b.centre().x() + 1, b.centre().y() + 1);
                    SkyPosition under = page.host().projection().toSky(b.centre().x(), b.centre().y());
                    SkyPosition empty = page.host().projection().toSky(MONITOR_W * 0.30, MONITOR_H * 0.35);
                    result[0] = hit.map(ReferenceInk.BodyPlacement::identity).orElse("none");
                    result[1] = under;
                    result[2] = empty;
                    return null;
                });
            } catch (Exception e) {
                throw new RuntimeException(e);
            }
        });
        SkyPosition under = (SkyPosition) result[1];
        SkyPosition truth = seen.get(target).at();
        p(f("Evening case, Hammer, ecliptic orientation. A pointer one pixel off %s's mark:"
                + " `selectableBodyAt` answers **%s**; the production pixel-to-sky route"
                + " (`ChartModuleHost.projection().toSky`) at the mark's centre answers %s, %.4f"
                + " degrees from the module's position.", target, result[0], under,
                under.separationDegrees(truth)));
        p("");
        for (Object[] leg : new Object[][] {{target, truth}, {"an empty position", result[2]}}) {
            SkyPosition centre = (SkyPosition) leg[1];
            double[] offset = new double[2];
            SwingUtilities.invokeAndWait(() -> {
                ChartComponent chart = new ChartComponent(Atlas.assembler(), PageText.in(
                        juranometria.ui.language.InterfaceText.forLanguage("en")));
                chart.setSize(1200, 800);
                chart.setViewState(ChartViewState.DEFAULT.recenteredAt(centre).withFieldWidth(60.0));
                ChartScene scene = chart.currentScene();
                offset[0] = scene.viewport().centre().separationDegrees(centre);
                offset[1] = scene.viewport().fieldWidthDegrees();
                BufferedImage image = new BufferedImage(1200, 800, BufferedImage.TYPE_INT_RGB);
                Graphics2D g = image.createGraphics();
                chart.paint(g);
                g.dispose();
                try {
                    ImageIO.write(image, "png", OUT.resolve("journey-detail-"
                            + (leg[0].equals(target) ? "body" : "position") + ".png").toFile());
                } catch (IOException e) {
                    throw new java.io.UncheckedIOException(e);
                }
            });
            p(f("- Enter an ordinary chart at %s: the chart opens centred %.6f degrees from it,"
                    + " field %.0f degrees, by the production projection for that field"
                    + " (`journey-detail-%s.png`).", leg[0], offset[0], offset[1],
                    leg[0].equals(target) ? "body" : "position"));
        }
        p("");
    }
