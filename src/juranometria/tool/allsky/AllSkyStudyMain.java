    /** Most of these positions inside any cap of this radius, centres on a 1-degree grid. */
    static int bestCap(List<SkyPosition> points, double radius) {
        int best = 0;
        for (int dec = -90; dec <= 90; dec++) {
            int step = Math.max(1, (int) Math.round(1.0 / Math.max(0.02, Math.cos(Math.toRadians(dec)))));
            for (int ra = 0; ra < 360; ra += step) {
                SkyPosition c = new SkyPosition(ra, dec);
                int n = 0;
                for (SkyPosition q : points) {
                    if (c.separationDegrees(q) <= radius) {
                        n++;
                    }
                }
                best = Math.max(best, n);
            }
        }
        return best;
    }

