    private static Drawn draw(Spec spec, AllSkyCases.Case c, AllSkyComposition.Services services,
                              SkyPosition chartCentre) throws Exception {
        Observer observer = AllSkyCases.oslo(c.instant());
        SkyPosition sun = new AllSkyCases(services).bodies(observer).get("sun").at();
        double central = spec.meridian().longitude(spec.orientation(), observer, sun, chartCentre);
        AllSkyMap map = new AllSkyMap(spec.form(), spec.orientation(), central);
        AllSkyProjection projection = new AllSkyProjection(map);
        PageText words = AllSkyStudyWords.in(spec.language());
        AllSkyComposition.Ask ask = new AllSkyComposition.Ask(observer, spec.palette(), words,
                LIMIT, true, spec.subdue(), spec.widthPx(), spec.heightPx());
        Drawn[] out = new Drawn[1];
        SwingUtilities.invokeAndWait(() -> {
            try {
                AllSkyComposition.Page page = AllSkyComposition.paint(projection, ask, services);
                out[0] = Projections.drawnForStudy(projection, () -> measure(spec, map, page, words));
                Graphics2D g = page.image().createGraphics();
                AllSkyStudyInk.paint(g, new AllSkyStudyInk.Frame(map, spec.widthPx(), spec.heightPx()),
                        spec.palette(), observer, true);
                AllSkyStudyInk.caption(g, spec.widthPx(), spec.palette(), spec.language().equals("en")
                        ? "Study ink: outline, ecliptic, equator, horizon"
                        : "Studieblekk: omriss, ekliptikk, ekvator, horisont");
                g.dispose();
                ImageIO.write(page.image(), "png", OUT.resolve(spec.name() + ".png").toFile());
            } catch (Exception e) {
                throw new RuntimeException(spec.name(), e);
            }
        });
        return out[0];
    }

    private static Drawn measure(Spec spec, AllSkyMap map, AllSkyComposition.Page page,
                                 PageText words) {
        ChartComponent chart = page.chart();
        ChartScene scene = chart.currentScene();
        Map<String, ReferenceInk.BodyPlacement> bodies = new LinkedHashMap<>();
        for (ReferenceInk.BodyPlacement b : chart.renderedBodies()) {
            bodies.put(b.identity(), b);
        }
        ChartRenderer renderer = new ChartRenderer(StarSizePolicy.DEFAULT, words);
        ChartOptions options = chart.drawnOptions();
        double jump = 0.4 * spec.widthPx();
        int figureJumps = 0;
        List<String> stranded = new ArrayList<>();
        for (ChartRenderer.FigureInk ink : renderer.figureInk(scene, options).values()) {
            figureJumps += jumps(ink.ink().getPathIterator(null), jump);
            if (ink.nameAnchor() != null
                    && nearestInk(ink.ink().getPathIterator(null), ink.nameAnchor()) > STRANDED_PX) {
                stranded.add(ink.constellationId());
            }
        }
        stranded.sort(String::compareTo);
        BufferedImage scratch = new BufferedImage(1, 1, BufferedImage.TYPE_INT_RGB);
        Graphics2D sg = scratch.createGraphics();
        sg.setFont(ChartRenderer.labelFont());
        EquatorialGrid.Grid grid = renderer.gridFor(sg.getFontMetrics(), scene, options);
        sg.dispose();
        int gridJumps = 0;
        for (List<List<PixelPoint>> family : List.of(grid.meridians(), grid.parallels())) {
            for (List<PixelPoint> run : family) {
                for (int i = 1; i < run.size(); i++) {
                    if (Math.abs(run.get(i).x() - run.get(i - 1).x()) > jump) {
                        gridJumps++;
                    }
                }
            }
        }
        int inSliver = 0;
        int drawn = 0;
        for (var star : scene.stars()) {
            if (star.magnitude() > LIMIT) {
                continue;
            }
            if (map.seamDistanceDegrees(star.position()) < AllSkyProjection.SEAM_SLIVER_DEGREES) {
                inSliver++;
            } else {
                drawn++;
            }
        }
        // Line ink is split by BelowHorizon's region (built from the horizon's drawn
        // runs); marks and labels are toned by their own position. Compare the region
        // with the true side of the horizon at sample pixels inside the outline.
        AllSkyStudyInk.Frame frame = new AllSkyStudyInk.Frame(map, spec.widthPx(), spec.heightPx());
        juranometria.render.BelowHorizon split = juranometria.render.BelowHorizon.of(
                new LocalSky(page.meridian().observer()).zenith(), scene);
        java.awt.Shape below = split.belowRegion();
        LocalSky sky = new LocalSky(page.meridian().observer());
        int sampled = 0;
        int wrong = 0;
        for (int py = 4; py < spec.heightPx(); py += 8) {
            for (int px = 4; px < spec.widthPx(); px += 8) {
                SkyPosition at = frame.sky(px, py);
                if (at == null) {
                    continue;
                }
                sampled++;
                if (below.contains(px, py) != (sky.altitudeDegrees(at) < 0)) {
                    wrong++;
                }
            }
        }
        return new Drawn(spec, map, bodies, figureJumps, gridJumps, inSliver, drawn,
                chart.getAccessibleContext().getAccessibleDescription(), stranded,
                sampled == 0 ? 0 : (double) wrong / sampled);
    }

    /** A name anchor this far from every point of its own figure stands nowhere near it. */
    static final double STRANDED_PX = 80.0;

    private static double nearestInk(PathIterator it, PixelPoint anchor) {
        double[] c = new double[6];
        double best = Double.MAX_VALUE;
        while (!it.isDone()) {
            int type = it.currentSegment(c);
            if (type == PathIterator.SEG_MOVETO || type == PathIterator.SEG_LINETO) {
                best = Math.min(best, Math.hypot(c[0] - anchor.x(), c[1] - anchor.y()));
            }
            it.next();
        }
        return best;
    }

    private static int jumps(PathIterator it, double limit) {
        double[] c = new double[6];
        double x = 0;
        int n = 0;
        while (!it.isDone()) {
            int type = it.currentSegment(c);
            if (type == PathIterator.SEG_LINETO && Math.abs(c[0] - x) > limit) {
                n++;
            }
            if (type == PathIterator.SEG_MOVETO || type == PathIterator.SEG_LINETO) {
                x = c[0];
            }
            it.next();
        }
        return n;
    }

