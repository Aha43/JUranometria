    private static void horizonSection(Map<String, AllSkyCases.Case> cases) {
        p("## 9. The winding horizon and Subdue below horizon");
        p("");
        p("The mathematical horizon is a great circle; on these maps it is a closed winding"
                + " curve. The seam is half a meridian, so every great circle not through the"
                + " map's poles crosses it exactly once - the horizon, the ecliptic and the"
                + " equator are each cut once on every page. With Subdue below horizon on, the"
                + " part of the map below the horizon is quieted. That is half the sky by"
                + " construction and, it turns out, exactly half of every candidate's area"
                + " too: the two halves are antipodal, and each form's area scale depends only"
                + " on the size of the latitude. What differs is where the quieted half lies"
                + " and how much the rectangle inflates it toward its poles. Central meridian:"
                + " observer's meridian.");
        p("");
        p("| case | form | orientation | horizon seam crossings | horizon length on the page (map widths) | share of the map's area below the horizon | ecliptic seam crossings |");
        p("|---|---|---|---|---|---|---|");
        for (AllSkyCases.Case c : cases.values()) {
            Observer o = AllSkyCases.oslo(c.instant());
            LocalSky sky = new LocalSky(o);
            for (AllSkyForm form : AllSkyForm.values()) {
                for (AllSkyOrientation orientation : AllSkyOrientation.values()) {
                    double central = AllSkyMeridian.midheaven(orientation, o);
                    AllSkyMap map = new AllSkyMap(form, orientation, central);
                    AllSkyStudyInk.Frame frame = new AllSkyStudyInk.Frame(map, 2000, 1000);
                    double length = 0;
                    for (List<double[]> run : AllSkyStudyInk.runs(frame, sky.horizon())) {
                        for (int i = 1; i < run.size(); i++) {
                            length += Math.hypot(run.get(i)[0] - run.get(i - 1)[0],
                                    run.get(i)[1] - run.get(i - 1)[1]);
                        }
                    }
                    int below = 0;
                    int inside = 0;
                    for (int py = 0; py < 1000; py += 4) {
                        for (int px = 0; px < 2000; px += 4) {
                            SkyPosition s = frame.sky(px + 2, py + 2);
                            if (s == null) {
                                continue;
                            }
                            inside++;
                            if (sky.altitudeDegrees(s) < 0) {
                                below++;
                            }
                        }
                    }
                    p(f("| %s | %s | %s | %d | %.2f | %.1f%% | %d |", c.id(), form.displayName(),
                            orientation.displayName(), AllSkyStudyInk.seamCrossings(map, sky.horizon()),
                            length / 2000.0, 100.0 * below / inside,
                            AllSkyStudyInk.seamCrossings(map, Ecliptic.circle())));
                }
            }
        }
        p("");
    }

