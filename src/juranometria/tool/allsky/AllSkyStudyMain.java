    /** Angle of local celestial north from page-up at a position, in degrees (0 = up). */
    static double northTilt(AllSkyStudyInk.Frame frame, SkyPosition at) {
        SkyPosition up = new SkyPosition(at.raDegrees(), Math.min(90.0, at.decDegrees() + 0.01));
        if (frame.map().seamDistanceDegrees(at) < 2 || frame.map().seamDistanceDegrees(up) < 2) {
            return 0.0;
        }
        double[] a = frame.pixel(at);
        double[] b = frame.pixel(up);
        return Math.abs(Math.toDegrees(Math.atan2(b[0] - a[0], a[1] - b[1])));
    }

