/**
 * Subdue below horizon, studied on production pages before any
 * production change (Sprint 55, issue #615).
 *
 * <p>Two things are measured. First, the inks: every palette ink's
 * contrast against its ground as drawn today and at three candidate
 * strengths of the released dimming rule - the body rule of #415,
 * {@code ChartRenderer.quiet}, which keeps 25 % of the ink's distance
 * from the ground - so the owner can rule on a strength by number.
 * Second, the look: production pages composed by the production
 * component with the meridian, ecliptic and Solar System modules
 * attached, written unchanged, and beside each a <em>mock-up</em> at
 * each candidate strength made by blending every pixel whose sky
 * position lies below the mathematical horizon towards the ground.
 *
 * <p>The mock-up is a pixel operation, not the rule: it dims the
 * horizon line and any furniture over the sky too, and it halves a
 * word that straddles the horizon - the two things the rule must not
 * do, shown so the rulings on labels and on the line can be made with
 * the problem in view. The pages themselves are production, byte for
 * byte: nothing about where anything is drawn changes here.
 */
public final class BelowHorizonStudyMain {

    private static final File DIR = new File("docs/studies/below-horizon");

    /** The gallery instant: Oslo on 2026-03-20 at 21:33 UTC, the Sun below the horizon. */
    private static final Instant WHEN = Instant.parse("2026-03-20T21:33:00Z");
    private static final Observer OSLO = new Observer(59.913, 10.752, WHEN);

    /** The released strength, and two candidates that keep more of the ink. */
    private static final double[] STRENGTHS = {0.25, 0.40, 0.55};

    private static final PageText ENGLISH = PageText.in(InterfaceText.forLanguage("en"));
    private static final PageText NORSK = PageText.in(InterfaceText.forLanguage("nb-NO"));

    private static final StringBuilder REPORT = new StringBuilder();

    private BelowHorizonStudyMain() {
    }

    private static void p(String line) {
        REPORT.append(line).append('\n');
    }

    public static void main(String[] args) throws Exception {
        REPORT.setLength(0);
        DIR.mkdirs();
        SolarSystemService service = SolarSystemService.load();
        LocalSky sky = new LocalSky(OSLO);
        SunObservation sun = (SunObservation) service.observe(Body.SUN, OSLO);

        p("# Subdue below horizon, on production pages");
        p("");
        p("Sprint 55, issue #615. Generated by `juranometria.tool.BelowHorizonStudyMain`"
                + " (`make below-horizon-study`) from compiled application classes: the pages"
                + " are the production composition - `ChartComponent` with the meridian,"
                + " ecliptic and Solar System modules attached - at the gallery instant,"
                + " Oslo 59.913° N 10.752° E, 2026-03-20 21:33 UTC, the Sun "
                + String.format(Locale.ROOT, "%.1f", sun.horizontal().altitudeDegrees())
                + "° below the horizon. Beside each production page stands a mock-up at each"
                + " candidate strength: every pixel whose sky position lies below the"
                + " mathematical horizon is blended towards the ground, keeping the stated"
                + " share of the ink's distance from it. The mock-up is a pixel operation,"
                + " not the rule: it dims the horizon line and the furniture over the sky as"
                + " well, and halves a word that straddles the horizon - what the rule must"
                + " not do, shown so that the rulings on labels and on the line are made"
                + " with the problem in view.");
        p("");
        p("## The inks, by number");
        p("");
        p("Contrast is the WCAG 2.x ratio (L1 + 0.05) / (L2 + 0.05) over sRGB relative"
                + " luminance, as `EmphasisStudyMain` measures it. The released body rule"
                + " (#415, `ChartRenderer.quiet`) keeps 25 % of an ink's distance from the"
                + " ground; 40 % and 55 % are the candidates that keep more.");
        p("");
        for (ChartPalette palette : ChartPalette.values()) {
            p("### " + palette.name().toLowerCase(Locale.ROOT).replace('_', ' '));
            p("");
            p("| ink | as drawn | kept 25 % (released) | kept 40 % | kept 55 % |");
            p("|---|---:|---:|---:|---:|");
            Color ground = palette.ground();
            for (String[] ink : new String[][] {
                    {"star ink", null}, {"text ink", null}, {"figure ink", null},
                    {"boundary ink", null}, {"constellation name ink", null},
                    {"grid ink", null}, {"grid label ink", null}, {"deep-sky outline", null},
                    {"nebula outline", null}, {"galaxy fill", null}, {"selection ink", null},
                    {"interaction ink", null}}) {
                Color c = inkOf(palette, ink[0]);
                StringBuilder row = new StringBuilder("| ").append(ink[0]).append(" | ")
                        .append(ratio(c, ground));
                for (double strength : STRENGTHS) {
                    row.append(" | ").append(ratio(blend(c, ground, strength), ground));
                }
                p(row.append(" |").toString());
            }
            p("");
        }

        p("## The pages");
        p("");
        p("Each page is production, unchanged; its mock-ups follow. The share of sky"
                + " pixels below the horizon on the page is stated, so a ruling knows how"
                + " much of a page the treatment touches.");
        p("");
        page("south-24", "The south, 24°: the horizon through the stars",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 24.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, true, false,
                "The ordinary field a reader meets: the mathematical horizon drawn, the"
                        + " meridian and the ecliptic drawn, the Sun and the Moon on; stars,"
                        + " their names and the constellation figures run across the horizon"
                        + " at full ink below it.");
        page("south-24-paper", "The same, on white paper",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 24.0, 8.0, null, null),
                ChartPalette.WHITE_PAPER, ENGLISH, service, true, false,
                "The paper palette: the subdued share has to read on the lighter ground too.");
        page("south-24-nb", "The same, in Norwegian",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 24.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, NORSK, service, true, false,
                "The Norwegian page: longer names cross the horizon in other places.");
        page("south-24-no-line", "The same, the horizon line off",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 24.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, false, false,
                "The horizon switch off: today nothing on this page says where the horizon"
                        + " is, and the Sun and the Moon are drawn at full ink. The mock-up"
                        + " shows the contrast boundary standing alone.");
        page("south-24-emphasis", "The same, figures and ecliptic emphasised",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 24.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, true, true,
                "Constellation figures and the ecliptic raised: the accents cross the"
                        + " horizon; the proposal keeps their colour and applies the same"
                        + " reduction below it.");
        page("east-8", "The east, 8°: names and figures at the horizon",
                new ChartViewState(sky.cardinal(Cardinal.EAST), 8.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, true, false,
                "A closer field where labels are dense: words that straddle the horizon"
                        + " are the labels case.");
        page("sun-3", "The Sun below the horizon, 3°",
                new ChartViewState(sun.astrometricJ2000(), 3.0, 8.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, true, false,
                "The motivating page: today the Sun alone is dimmed while every star around"
                        + " it stays bright, so the body reads as hidden rather than as below"
                        + " the horizon.");
        page("globe-180", "The whole sky, 180°",
                new ChartViewState(sky.cardinal(Cardinal.SOUTH), 180.0, 5.0, null, null),
                ChartPalette.BLACK_SKY, ENGLISH, service, true, false,
                "The globe: the horizon as a curve through the disc; below it, half the sky.");
        System.out.print(REPORT);
    }

    private static Color inkOf(ChartPalette palette, String name) {
        return switch (name) {
            case "star ink" -> palette.starInk();
            case "text ink" -> palette.textInk();
            case "figure ink" -> palette.figureInk();
            case "boundary ink" -> palette.boundaryInk();
            case "constellation name ink" -> palette.constellationNameInk();
            case "grid ink" -> palette.gridInk();
            case "grid label ink" -> palette.gridLabelInk();
            case "deep-sky outline" -> palette.deepSkyOutline();
            case "nebula outline" -> palette.nebulaOutline();
            case "galaxy fill" -> palette.galaxyFill();
            case "selection ink" -> palette.selectionInk();
            case "interaction ink" -> palette.interactionInk();
            default -> throw new IllegalArgumentException(name);
        };
    }

    /** An ink moved towards the ground, keeping this share of its distance: the released rule's shape. */
    static Color blend(Color ink, Color ground, double kept) {
        return new Color(
                (int) Math.round(ground.getRed() + (ink.getRed() - ground.getRed()) * kept),
                (int) Math.round(ground.getGreen() + (ink.getGreen() - ground.getGreen()) * kept),
                (int) Math.round(ground.getBlue() + (ink.getBlue() - ground.getBlue()) * kept));
    }

    private static String ratio(Color one, Color other) {
        return String.format(Locale.ROOT, "%.2f:1", contrast(one, other));
    }

    /** The WCAG 2.x contrast ratio over sRGB relative luminance. */
    static double contrast(Color one, Color other) {
        double a = luminance(one);
        double b = luminance(other);
        return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
    }

    private static double luminance(Color c) {
        return 0.2126 * linear(c.getRed()) + 0.7152 * linear(c.getGreen())
                + 0.0722 * linear(c.getBlue());
    }

    private static double linear(int channel) {
        double c = channel / 255.0;
        return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
    }

    private static void page(String name, String title, ChartViewState state,
                             ChartPalette palette, PageText words, SolarSystemService service,
                             boolean horizonLine, boolean emphasis, String caption)
            throws Exception {
        ChartComponent[] holder = new ChartComponent[1];
        SwingUtilities.invokeAndWait(() -> {
            holder[0] = new ChartComponent(Atlas.assembler(), words);
            holder[0].setSize(900, 700);
            holder[0].setChartOptions(ChartOptions.DEFAULTS.withPalette(palette));
            holder[0].setViewState(state);
            MeridianModule meridian = new MeridianModule(OSLO);
            meridian.showing(true, horizonLine, false);
            holder[0].overlays().offer(MeridianModule.ID, meridian::contributedGeometry);
            EclipticModule ecliptic = new EclipticModule();
            ecliptic.showing(true);
            holder[0].overlays().offer(EclipticModule.ID, ecliptic::contributedGeometry);
            SolarSystemModule solar = new SolarSystemModule(() -> OSLO, () -> service,
                    meridian::horizonShowing);
            solar.sunShowing(true);
            solar.moonShowing(true);
            holder[0].overlays().offer(SolarSystemModule.ID, solar::contributedGeometry);
            if (emphasis) {
                holder[0].toggleEmphasis(ChartStructure.CONSTELLATION_FIGURES);
                holder[0].toggleEmphasis(ChartStructure.ECLIPTIC);
            }
        });
        SwingUtilities.invokeAndWait(() -> { });
        SwingUtilities.invokeAndWait(() -> { });
        ChartComponent chart = holder[0];
        BufferedImage image = new BufferedImage(900, 700, BufferedImage.TYPE_INT_RGB);
        SwingUtilities.invokeAndWait(() -> {
            Graphics2D g = image.createGraphics();
            try {
                chart.paint(g);
            } finally {
                g.dispose();
            }
        });
        ImageIO.write(image, "png", new File(DIR, name + ".png"));

        // The sky below the horizon, pixel by pixel, from the page's own
        // inverse projection: null where the page has no sky.
        ChartScene scene = chart.currentScene();
        LocalSky sky = new LocalSky(OSLO);
        int offsetX = chart.pageOffsetX();
        int offsetY = chart.pageOffsetY();
        boolean[][] below = new boolean[image.getHeight()][image.getWidth()];
        int skyPixels = 0;
        int belowPixels = 0;
        for (int y = 0; y < image.getHeight(); y++) {
            for (int x = 0; x < image.getWidth(); x++) {
                SkyPosition at = ChartHitTest.skyAt(scene, x - offsetX + 0.5, y - offsetY + 0.5);
                if (at == null) {
                    continue;
                }
                skyPixels++;
                if (sky.altitudeDegrees(at) < 0.0) {
                    below[y][x] = true;
                    belowPixels++;
                }
            }
        }
        Color ground = palette.ground();
        List<String> mockups = new ArrayList<>();
        for (double strength : STRENGTHS) {
            BufferedImage out = new BufferedImage(image.getWidth(), image.getHeight(),
                    BufferedImage.TYPE_INT_RGB);
            int changed = 0;
            for (int y = 0; y < image.getHeight(); y++) {
                for (int x = 0; x < image.getWidth(); x++) {
                    int rgb = image.getRGB(x, y);
                    if (below[y][x]) {
                        int dimmed = blend(new Color(rgb), ground, strength).getRGB();
                        if (dimmed != rgb) {
                            changed++;
                        }
                        rgb = dimmed;
                    }
                    out.setRGB(x, y, rgb);
                }
            }
            String file = String.format(Locale.ROOT, "%s-kept-%02d.png", name,
                    Math.round(strength * 100));
            ImageIO.write(out, "png", new File(DIR, file));
            mockups.add(String.format(Locale.ROOT, "![](%s) kept %d %%: %d pixels changed",
                    file, Math.round(strength * 100), changed));
        }
        p("## " + title);
        p("");
        p("![](" + name + ".png)");
        p("");
        p(caption + String.format(Locale.ROOT, " Sky pixels on the page: %d, of which %d"
                + " (%.1f %%) lie below the mathematical horizon.", skyPixels, belowPixels,
                skyPixels == 0 ? 0.0 : 100.0 * belowPixels / skyPixels));
        p("");
        for (String mockup : mockups) {
            p(mockup);
            p("");
        }
    }
}
