    private record Measured(int ticksOnPage, double low, double high, boolean offered,
                            MeridianReadout.Sample a,
                            BufferedImage page, ChartModuleHost host, List<MeridianReadout.Sample> visible) {
    }

    private static Measured measure(SkyPosition centre, double field, boolean north) throws Exception {
        return measure(centre, field, north, ENGLISH, ChartPalette.WHITE_PAPER);
    }

    private static Measured measure(SkyPosition centre, double field, boolean north, PageText words,
                                    ChartPalette palette) throws Exception {
        ChartComponent[] chart = new ChartComponent[1];
        ChartModuleHost[] host = new ChartModuleHost[1];
        SwingUtilities.invokeAndWait(() -> {
            chart[0] = new ChartComponent(Atlas.assembler(), words);
            chart[0].setSize(900, 700);
            chart[0].setChartOptions(ChartOptions.DEFAULTS.withPalette(palette));
            chart[0].setViewState(new ChartViewState(centre, field,
                    ChartViewState.defaultMagnitudeFor(field)));
            List<NavigationRequest> asked = new ArrayList<>();
            host[0] = new ChartModuleHost(chart[0], new SelectionModel(), asked::add);
            MeridianModule module = host[0].attach(new MeridianModule(OSLO));
            module.showing(true, true, false);
            module.ticksShowing(true);
        });
        BufferedImage page = paint(chart[0]);
        LocalSky sky = new LocalSky(OSLO);
        int ticks = 0;
        for (double altitude : MeridianModule.Ticks.PROPOSED.altitudes()) {
            double[] px = host[0].projection().toPage(sky.onMeridian(altitude, north)).orElse(null);
            if (px != null && inside(px)) {
                ticks++;
            }
        }
        List<MeridianReadout.Sample> visible = new ArrayList<>();
        for (double altitude = 0.0; altitude <= 90.0 + 1e-9; altitude += 0.05) {
            double a = Math.min(altitude, 90.0);
            double[] px;
            try {
                px = host[0].projection().toPage(sky.onMeridian(a, north)).orElse(null);
            } catch (RuntimeException refused) {
                px = null;
            }
            if (px != null && inside(px)) {
                visible.add(new MeridianReadout.Sample(a, px[0], px[1]));
            }
        }
        double low = visible.stream().mapToDouble(MeridianReadout.Sample::altitudeDegrees).min().orElse(Double.NaN);
        double high = visible.stream().mapToDouble(MeridianReadout.Sample::altitudeDegrees).max().orElse(Double.NaN);
        boolean offered = !visible.isEmpty() && high > 0.0
                && !MeridianReadout.aRuledTickIsVisible(visible, MeridianModule.Ticks.PROPOSED);
        MeridianReadout.Sample a = offered
                ? MeridianReadout.nearestTheCentre(visible, CX, CY)
                        .filter(s -> MeridianReadout.statable(
                                MeridianReadout.roundedToTheDegree(s.altitudeDegrees())))
                        .orElse(null)
                : null;
        return new Measured(ticks, low, high, offered, a, page, host[0], visible);
    }

    private static boolean inside(double[] px) {
        return px[0] >= 0 && px[1] >= 0 && px[0] < 900 && px[1] < 700;
    }

    private static void page(String name, SkyPosition centre, double field, boolean north,
                             PageText words, ChartPalette palette, String caption) throws Exception {
        Measured m = measure(centre, field, north, words, palette);
        BufferedImage image = m.page;
        String drawn = "nothing: a ruled tick is on the page";
        int overlap = -1;
        String mockFigure = "—";
        if (m.offered && m.a != null) {
            mockFigure = words.altitudeTick(MeridianReadout.roundedToTheDegree(m.a.altitudeDegrees()));
            overlap = figureRoom(image, m, mockFigure, palette);
            drawn = "production ink at " + pixel(m.a) + ", figure " + mockFigure;
        } else if (m.offered) {
            drawn = "nothing: no statable altitude on the visible line";
        }
        ImageIO.write(image, "png", new File(DIR, name + ".png"));
        p("| ![](" + name + ".png) " + name + " (" + caption + ") | " + figure(field) + "° | " + m.ticksOnPage
                + " | " + (m.visible.isEmpty() ? "none" : fmt(m.low, 2) + "°–" + fmt(m.high, 2) + "°")
                + " | " + (m.a == null ? "—" : fmt(m.a.altitudeDegrees(), 2) + "° at " + pixel(m.a))
                + " | " + (m.a == null ? "—" : figure(MeridianReadout.roundedToTheDegree(m.a.altitudeDegrees())) + "°")
                + " | " + drawn + " |");
        q("| " + name + " | " + mockFigure + " | " + (overlap < 0 ? "—" : Integer.toString(overlap)) + " |");
    }

    /** How much of the page's own ink the figure's box beside the mark meets - the placement's reason to refuse it. */
    private static int figureRoom(BufferedImage image, Measured m, String figureText, ChartPalette palette) {
        MeridianReadout.Sample at = m.a;
        // The line's direction: the visible sample nearest to the mark, a little along.
        MeridianReadout.Sample ahead = null;
        for (MeridianReadout.Sample s : m.visible) {
            if (Math.abs(s.altitudeDegrees() - at.altitudeDegrees() - 0.2) < 0.03) {
                ahead = s;
            }
        }
        if (ahead == null) {
            for (MeridianReadout.Sample s : m.visible) {
                if (Math.abs(s.altitudeDegrees() - at.altitudeDegrees() + 0.2) < 0.03) {
                    ahead = s;
                }
            }
        }
        double dx = ahead == null ? 0 : ahead.x() - at.x();
        double dy = ahead == null ? 1 : ahead.y() - at.y();
        double len = Math.hypot(dx, dy);
        double nx = len == 0 ? 1 : -dy / len;
        double ny = len == 0 ? 0 : dx / len;
        Graphics2D g = image.createGraphics();
        int overlap = 0;
        try {
            g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
            g.setFont(new Font(Font.SANS_SERIF, Font.PLAIN, 11));
            java.awt.geom.Rectangle2D box = g.getFontMetrics().getStringBounds(figureText, g);
            int tx = (int) Math.round(at.x() + 7);
            int ty = (int) Math.round(at.y() - 4);
            Color ground = palette == ChartPalette.BLACK_SKY ? Color.BLACK : Color.WHITE;
            for (int y = (int) (ty + box.getY()); y < ty + box.getY() + box.getHeight(); y++) {
                for (int x = tx; x < tx + box.getWidth(); x++) {
                    if (x >= 0 && y >= 0 && x < image.getWidth() && y < image.getHeight()
                            && (image.getRGB(x, y) & 0xffffff) != (ground.getRGB() & 0xffffff)) {
                        overlap++;
                    }
                }
            }
        } finally {
            g.dispose();
        }
        return overlap;
    }

    private static String pixel(MeridianReadout.Sample s) {
        return "(" + fmt(s.x(), 1) + ", " + fmt(s.y(), 1) + ")";
    }

    private static String figure(double degrees) {
        return degrees == Math.rint(degrees) ? Long.toString(Math.round(degrees))
                : String.format(Locale.ROOT, "%.1f", degrees);
    }

    private static String fmt(double value, int decimals) {
        return String.format(Locale.ROOT, "%." + decimals + "f", value);
    }

    private static BufferedImage paint(ChartComponent chart) throws Exception {
        BufferedImage image = new BufferedImage(900, 700, BufferedImage.TYPE_INT_RGB);
        SwingUtilities.invokeAndWait(() -> {
            Graphics2D g = image.createGraphics();
            try {
                chart.paint(g);
            } finally {
                g.dispose();
            }
        });
        return image;
    }

    private static void p(String line) {
        REPORT.append(line).append('\n');
    }

    private static void q(String line) {
        PLATFORM.append(line).append('\n');
    }
