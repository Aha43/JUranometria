package juranometria.tool;

import java.io.IOException;

import juranometria.solar.VenusService;

/**
 * The Venus service's accuracy against JPL Horizons and Espenak's named
 * events, as a kept report (issue #501): every quantity's worst
 * difference by era beside the target ruled on #500, the side of the
 * Sun on every row, χ against Horizons' own Sun and Venus, and the
 * published conjunctions and greatest elongations. Deterministic: the
 * service and the fixtures are fixed, the numbers are rounded. Written
 * to {@code docs/studies/venus/service-accuracy.md} by
 * {@code make venus-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class VenusAccuracyReportMain {

    private VenusAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        VenusService service = VenusService.load();
        VenusComparison.Result result = new VenusComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Venus service against Horizons and Espenak (#501)\n\n")
                .append("Generated by `juranometria.tool.VenusAccuracyReportMain`")
                .append(" (`make venus-accuracy-report`) from the service over the")
                .append(" bundled Solar System and planets packs and the Horizons responses")
                .append(" committed under `horizons/`; `VenusReferenceVectorTest` and")
                .append(" `VenusNamedEventsTest` hold these numbers to the targets ruled on")
                .append(" #500. Observers at sea level, UT1 = UTC, the atlas's own time scales,")
                .append(" the Sun's gravitational deflection in every apparent place, the")
                .append(" Moon's S-T-O phase angle, the solid-body radius. Venus answers from ")
                .append(service.firstDay()).append(" to ").append(service.lastDay())
                .append(".\n\n")
                .append(VenusComparison.report(result));
        System.out.print(out);
    }
}
