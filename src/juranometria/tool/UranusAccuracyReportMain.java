package juranometria.tool;

import java.io.IOException;

import juranometria.solar.UranusService;

/**
 * The Uranus service's accuracy against JPL Horizons and Espenak's named
 * events, as a kept report (issue #634): every quantity's worst difference
 * by era beside the target ruled on #633, the moons' states against
 * Horizons' codes, and the published oppositions and conjunctions.
 * Deterministic: the service and the fixtures are fixed, the numbers
 * rounded. Written to {@code docs/studies/uranus-system/service-accuracy.md}
 * by {@code make uranus-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class UranusAccuracyReportMain {

    private UranusAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        UranusService service = UranusService.load();
        UranusComparison.Result result = new UranusComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Uranus service against Horizons and Espenak (#634)\n\n")
                .append("Generated by `juranometria.tool.UranusAccuracyReportMain`")
                .append(" (`make uranus-accuracy-report`) from the service over the bundled Solar System")
                .append(" and Uranus System packs and the Horizons responses committed under `horizons/`;")
                .append(" `UranusReferenceVectorTest` holds these numbers to the targets ruled on #633.")
                .append(" Observers at sea level, UT1 = UTC, the atlas's own time scales, the Sun's")
                .append(" deflection in every apparent place, the phase angle held to Horizons' `phi`")
                .append(" (U-5), the IAU pole with no periodic terms (U-4), Uranus the DE442 barycentre")
                .append(" (U-1a, U-2). Uranus answers from ").append(service.firstDay()).append(" to ")
                .append(service.lastDay()).append("; Miranda, Ariel, Umbriel, Titania and Oberon from ")
                .append(service.moonsFirstDay()).append(" to ").append(service.moonsLastDay())
                .append(".\n\n")
                .append(UranusComparison.report(result));
        System.out.print(out);
    }
}
