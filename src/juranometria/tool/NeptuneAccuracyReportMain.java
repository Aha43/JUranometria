package juranometria.tool;

import java.io.IOException;

import juranometria.solar.NeptuneService;

/**
 * The Neptune service's accuracy against JPL Horizons and Espenak's named
 * events, as a kept report (issue #655): every quantity's worst difference
 * by era beside the target ruled on #654, the moons' states against
 * Horizons' codes, and the published oppositions and conjunctions.
 * Deterministic: the service and the fixtures are fixed, the numbers
 * rounded. Written to {@code docs/studies/neptune-system/service-accuracy.md}
 * by {@code make neptune-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class NeptuneAccuracyReportMain {

    private NeptuneAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        NeptuneService service = NeptuneService.load();
        NeptuneComparison.Result result = new NeptuneComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Neptune service against Horizons and Espenak (#655)\n\n")
                .append("Generated by `juranometria.tool.NeptuneAccuracyReportMain`")
                .append(" (`make neptune-accuracy-report`) from the service over the bundled Solar System")
                .append(" and Neptune System packs and the Horizons responses committed under `horizons/`;")
                .append(" `NeptuneReferenceVectorTest` holds these numbers to the targets ruled on #654.")
                .append(" Observers at sea level, UT1 = UTC, the atlas's own time scales, the Sun's")
                .append(" deflection in every apparent place, the phase angle held to Horizons' `phi`")
                .append(" (N-5), the IAU pole with its periodic term (N-4), Neptune the DE442 barycentre")
                .append(" (N-1a, N-2). Neptune answers from ").append(service.firstDay()).append(" to ")
                .append(service.lastDay()).append("; Triton and Nereid from ")
                .append(service.moonsFirstDay()).append(" to ").append(service.moonsLastDay())
                .append(".\n\n")
                .append(NeptuneComparison.report(result));
        System.out.print(out);
    }
}
