    private static void row(StringBuilder rows, String when, String words) {
        rows.append("| ").append(when.isEmpty() ? "" : when).append(" | ").append(cell(words)).append(" |\n");
    }

    private static void draw(JComponent content, int width, Path to) throws Exception {
        BufferedImage sheet = SheetCapture.take(content,
                SheetCapture.fixedCanvas(() -> {
                    content.setSize(width, content.getPreferredSize().height);
                    layoutDeeply(content);
                    content.setSize(width, content.getPreferredSize().height);
                    layoutDeeply(content);
                }),
                SheetCapture.Premise.none(),
                () -> {
                    BufferedImage drawn = new BufferedImage(width, content.getHeight(), BufferedImage.TYPE_INT_RGB);
                    Graphics2D g = drawn.createGraphics();
                    try {
                        g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING,
                                RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
                        g.setColor(Color.WHITE);
                        g.fillRect(0, 0, width, content.getHeight());
                        content.paint(g);
                    } finally {
                        g.dispose();
                    }
                    return drawn;
                });
        ImageIO.write(sheet, "png", to.toFile());
    }

    private static void layoutDeeply(Container from) {
        from.doLayout();
        for (Component child : from.getComponents()) {
            if (child instanceof Container nested) {
                layoutDeeply(nested);
            }
        }
    }

    private static String describe(String surface, JComponent content) {
        StringBuilder rows = new StringBuilder("### ").append(surface).append("\n\n")
                .append("| kind | shown | spoken as | explained as |\n|---|---|---|---|\n");
        for (Component control : reading(content)) {
            String kind;
            String shown;
            if (control instanceof JLabel label) {
                kind = "label";
                shown = label.getText();
            } else if (control instanceof AbstractButton button) {
                kind = "button";
                shown = button.getText();
            } else if (control instanceof JComboBox<?> box) {
                kind = "selector";
                List<String> items = new ArrayList<>();
                for (int i = 0; i < box.getItemCount(); i++) {
                    items.add(String.valueOf(box.getItemAt(i)));
                }
                shown = String.join(" · ", items);
            } else if (control instanceof JTextField field) {
                kind = "field";
                shown = field.getText();
            } else if (control instanceof JTextArea area) {
                kind = "text";
                shown = area.getText();
            } else if (control instanceof javax.swing.JTree tree) {
                kind = "tree";
                List<String> rowsShown = new ArrayList<>();
                for (int r = 0; r < tree.getRowCount(); r++) {
                    Object node = tree.getPathForRow(r).getLastPathComponent();
                    Component cell = tree.getCellRenderer().getTreeCellRendererComponent(tree, node,
                            false, tree.isExpanded(r), false, r, false);
                    rowsShown.add(cell instanceof JLabel l ? l.getText() : String.valueOf(node));
                }
                shown = String.join(" · ", rowsShown);
            } else {
                continue;
            }
            JComponent spoken = (JComponent) control;
            if ((shown == null || shown.isBlank()) && spoken.getAccessibleContext().getAccessibleName() == null) {
                continue;
            }
            rows.append("| ").append(kind)
                    .append(" | ").append(cell(shown))
                    .append(" | ").append(cell(spoken.getAccessibleContext().getAccessibleName()))
                    .append(" | ").append(cell(spoken.getAccessibleContext().getAccessibleDescription()))
                    .append(" |\n");
        }
        return rows.append('\n').toString();
    }

    private static String cell(String text) {
        return text == null || text.isBlank() ? "—"
                : text.replace("|", "\\|").replace("\n", " / ");
    }

    private static List<Component> reading(Container from) {
        List<Component> found = new ArrayList<>();
        for (Component child : from.getComponents()) {
            if (!child.isVisible()) {
                continue;
            }
            found.add(child);
            if (child instanceof Container nested) {
                found.addAll(reading(nested));
            }
        }
        return found;
    }
