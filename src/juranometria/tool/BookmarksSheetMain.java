        row(rows, "", words.say("bookmark.delete.folder.keep") + " · " + words.say("bookmark.delete.folder.all")
                + " · " + words.say("bookmark.add.cancel.label"));
        row(rows, "the library menu", words.say("bookmark.export.label") + " · " + words.say("bookmark.restore.label"));
        row(rows, "an export's suggested name", words.say("bookmark.export.name", "2026-11-03"));
        row(rows, "exporting over a file", words.say("bookmark.export.exists", "JUranometria bookmarks.json"));
        row(rows, "exported", words.say("bookmark.export.done", 3, 2, "JUranometria bookmarks.json"));
        row(rows, "restoring", words.say("bookmark.restore.question", "JUranometria bookmarks.json", 3, 2, 0, "6.2.0"));
        row(rows, "restored", words.say("bookmark.restore.done", 3, "bookmarks-before-restore-20261103T100000Z.json"));
