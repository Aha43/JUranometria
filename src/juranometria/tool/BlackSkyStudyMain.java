    // ---- the rule, executed --------------------------------------

    /**
     * WCAG relative luminance of an sRGB grey, the standard
     * linearization.
     */
    static double luminance(int grey) {
        double c = grey / 255.0;
        return c <= 0.04045 ? c / 12.92
                : Math.pow((c + 0.055) / 1.055, 2.4);
    }

    /** WCAG contrast ratio between an ink and its ground. */
    static double contrast(int ink, int ground) {
        double lighter = Math.max(luminance(ink), luminance(ground));
        double darker = Math.min(luminance(ink), luminance(ground));
        return (lighter + 0.05) / (darker + 0.05);
    }

    /**
     * The equal-contrast partner of a white-paper ink: the sRGB grey
     * whose contrast against black is what the ink's was against
     * white, chosen as the value whose luminance is nearest the
     * exact solution. Monotone, so the prominence order survives the
     * crossing by construction.
     */
    static int equalContrastOnBlack(int whitePaperGrey) {
        double target = 0.0525 / (luminance(whitePaperGrey) + 0.05)
                - 0.05;
        int best = 0;
        double error = Double.MAX_VALUE;
        for (int grey = 0; grey <= 255; grey++) {
            double e = Math.abs(luminance(grey) - target);
            if (e < error) {
                error = e;
                best = grey;
            }
        }
        return best;
    }

    private static void derivation() {
        System.out.println("## The rule: equal contrast, not"
                + " inversion");
        System.out.println();
        System.out.println("Every ink keeps the WCAG contrast ratio"
                + " against its ground that it earned on white paper:"
                + " for a paper ink of relative luminance *l*, the"
                + " black-sky partner is the grey nearest luminance"
                + " `0.0525 / (l + 0.05) - 0.05`. Because sRGB"
                + " luminance is non-linear, this is visibly not a"
                + " channel mirror - the mid-greys land dimmer than"
                + " `255 - v` would put them, which is exactly the"
                + " restrained light ink the issue asks for, falling"
                + " out of the rule rather than being tuned by hand."
                + " The mapping is monotone, so which ink is more"
                + " prominent than which is preserved without a"
                + " separate rule.");
        System.out.println();
        System.out.println("| ink | paper | ratio | derived | pinned"
                + " | ratio on black | channel mirror |");
        System.out.println("|---|---|---|---|---|---|---|");
        List<String> breaches = new ArrayList<>();
        for (Role role : ROLES) {
            int paper = role.ink().apply(ChartPalette.WHITE_PAPER)
                    .getRed();
            int pinned = role.ink().apply(ChartPalette.BLACK_SKY)
                    .getRed();
            int derived = equalContrastOnBlack(paper);
            System.out.printf(Locale.ROOT,
                    "| %s | %d | %.2f:1 | %d | %d | %.2f:1 | %d |%n",
                    role.name(), paper, contrast(paper, 255), derived,
                    pinned, contrast(pinned, 0), 255 - paper);
            if (derived != pinned) {
                breaches.add(role.name() + ": pinned " + pinned
                        + " but the rule derives " + derived);
            }
        }
        System.out.println();
        if (!breaches.isEmpty()) {
            breaches.forEach(b ->
                    System.out.println("PALETTE BREACH: " + b));
            throw new IllegalStateException(
                    "the pinned black-sky palette is not what the"
                            + " derivation rule produces: " + breaches);
        }
        System.out.println("The pinned `ChartPalette.BLACK_SKY` is"
                + " exactly what the rule derives, verified by this"
                + " run. Both grounds themselves are exact: paper"
                + " white 255, sky black 0.");
        System.out.println();
        System.out.println("The two values nearest their readability"
                + " thresholds:");
        System.out.println();
        int nebula = ChartPalette.BLACK_SKY.nebulaOutline().getRed();
        System.out.printf(Locale.ROOT, "- the nebula box, %d, scores"
                        + " %.2f:1 against the black ground - clear"
                        + " of the 3:1 floor the deep-sky vocabulary"
                        + " decision set, mirroring its 3.74:1 on"
                        + " paper;%n", nebula, contrast(nebula, 0));
        int fill = ChartPalette.BLACK_SKY.galaxyFill().getRed();
        System.out.printf(Locale.ROOT, "- the galaxy fill, %d, scores"
                + " %.2f:1 - the same deliberate whisper as its"
                + " 1.23:1 wash on paper, and its presence on a real"
                + " page is asserted below rather than assumed.%n",
                fill, contrast(fill, 0));
        if (contrast(nebula, 0) < 3.0) {
            throw new IllegalStateException("the nebula box has sunk"
                    + " under its 3:1 floor on black: "
                    + contrast(nebula, 0));
        }
        System.out.println();
    }

    private static void hierarchy() {
        System.out.println("## The hierarchy, preserved");
        System.out.println();
        System.out.println("Ink purposes ordered by contrast against"
                + " their ground - identical on both grounds, star"
                + " discs to galaxy fill:");
        System.out.println();
        List<Role> paperOrder = new ArrayList<>(ROLES);
        paperOrder.sort((a, b) -> Double.compare(
                contrast(b.ink().apply(ChartPalette.WHITE_PAPER)
                        .getRed(), 255),
                contrast(a.ink().apply(ChartPalette.WHITE_PAPER)
                        .getRed(), 255)));
        List<Role> blackOrder = new ArrayList<>(ROLES);
        blackOrder.sort((a, b) -> Double.compare(
                contrast(b.ink().apply(ChartPalette.BLACK_SKY)
                        .getRed(), 0),
                contrast(a.ink().apply(ChartPalette.BLACK_SKY)
                        .getRed(), 0)));
        for (int i = 0; i < paperOrder.size(); i++) {
            System.out.printf("%d. %s%n", i + 1,
                    paperOrder.get(i).name());
            if (!paperOrder.get(i).name()
                    .equals(blackOrder.get(i).name())) {
                throw new IllegalStateException("the prominence order"
                        + " differs between grounds at position "
                        + (i + 1) + ": " + paperOrder.get(i).name()
                        + " vs " + blackOrder.get(i).name());
            }
        }
        System.out.println();
    }

    // ---- the pages, rendered and accounted -----------------------

    private static void pages(ChartRenderer renderer, File outDir)
            throws Exception {
        System.out.println("## The pages, and every pixel accounted");
        System.out.println();
        System.out.println("Each page is rendered in both palettes"
                + " (900x700; committed beside this document as"
                + " `<page>-paper.png` and `<page>-black.png`). For"
                + " the black render, three contracts, asserted:"
                + " every pixel is grey; every colour covering at"
                + " least 0.5% of the page is a reviewed palette"
                + " value (an accidental white island or a furniture"
                + " block on the wrong ground is thousands of"
                + " pixels; the antialiased rim of a long feature is"
                + " a legitimate concentration of a single"
                + " intermediate grey - the first run caught 531"
                + " pixels of grey 1 along M31's ellipse rim, honest"
                + " compositing a naive floor misread); and every"
                + " remaining colour is counted as antialiasing, not"
                + " waved through. Then the two renders are compared"
                + " structurally, pixel for pixel, each classified"
                + " ground / exact ink / antialiased: compositing"
                + " against the wrong ground would put antialiasing"
                + " where the paper render has none, so the"
                + " classification agreement is the halo check made"
                + " executable. \"Mask\" is the set of non-ground"
                + " pixels; its residual disagreement is rounding at"
                + " edges where coverage is marginal against one"
                + " ground but not the other.");
        System.out.println();
        System.out.println("| page | why | palette px | AA px |"
                + " AA greys | class agreement | mask agreement |"
                + " mask differs |");
        System.out.println("|---|---|---|---|---|---|---|---|");

        for (Page page : PAGES) {
            ChartViewState state = new ChartViewState(
                    new SkyPosition(page.ra(), page.dec()),
                    page.field(), 8.0, null, null);
            ChartScene scene = Atlas.assembler().assemble(
                    state, 900, 700);
            ChartOptions base = page.key()
                    ? new ChartOptions(true, true, true, true, true,
                            true, true, true, true, true, true, true,
                            true, true, true, true)
                    : ChartOptions.DEFAULTS;
            BufferedImage paper = renderer.renderToImage(scene, base);
            BufferedImage black = renderer.renderToImage(scene,
                    base.withPalette(ChartPalette.BLACK_SKY));
            ImageIO.write(paper, "png",
                    new File(outDir, page.name() + "-paper.png"));
            ImageIO.write(black, "png",
                    new File(outDir, page.name() + "-black.png"));

            accounted(page, paper, black);
        }
        System.out.println();
        System.out.println("No page carries a bulk colour outside"
                + " the reviewed palette and no pixel on any page is"
                + " other than grey - both asserted, the run fails"
                + " on a breach. The classification agreement is the"
                + " wrong-ground check: a halo would be antialiasing"
                + " on the black render where the paper render has"
                + " ground or exact ink, and the residual"
                + " disagreement above is confined to edge rounding,"
                + " the same order as the mask residual.");
        System.out.println();
    }

    /** ground / exact palette ink / antialiased blend. */
    private static int classify(int rgb, int ground,
                                java.util.Set<Integer> palette) {
        if (rgb == ground) {
            return 0;
        }
        return palette.contains(rgb) ? 1 : 2;
    }

    private static java.util.Set<Integer> inksOf(ChartPalette which) {
        java.util.Set<Integer> palette = new java.util.HashSet<>();
        for (Role role : ROLES) {
            palette.add(role.ink().apply(which).getRGB());
        }
        return palette;
    }

    private static void accounted(Page page, BufferedImage paper,
                                  BufferedImage black) {
        java.util.Set<Integer> palette = inksOf(ChartPalette.BLACK_SKY);
        int ground = ChartPalette.BLACK_SKY.ground().getRGB();
        palette.add(ground);

        Map<Integer, Integer> census = new TreeMap<>();
        int total = black.getWidth() * black.getHeight();
        for (int y = 0; y < black.getHeight(); y++) {
            for (int x = 0; x < black.getWidth(); x++) {
                int rgb = black.getRGB(x, y);
                int r = (rgb >> 16) & 0xff;
                int g = (rgb >> 8) & 0xff;
                int b = rgb & 0xff;
                if (r != g || g != b) {
                    throw new IllegalStateException(page.name()
                            + ": non-grey pixel at " + x + "," + y
                            + ": " + Integer.toHexString(rgb));
                }
                census.merge(rgb, 1, Integer::sum);
            }
        }
        int bulkFloor = (int) Math.ceil(total * 0.005);
        long palettePixels = 0;
        int aaPixels = 0;
        int aaGreys = 0;
        for (Map.Entry<Integer, Integer> colour : census.entrySet()) {
            if (palette.contains(colour.getKey())) {
                palettePixels += colour.getValue();
            } else if (colour.getValue() >= bulkFloor) {
                throw new IllegalStateException(page.name()
                        + ": bulk colour outside the reviewed palette:"
                        + " grey " + (colour.getKey() & 0xff) + " on "
                        + colour.getValue() + " pixels");
            } else {
                aaPixels += colour.getValue();
                aaGreys++;
            }
        }

        java.util.Set<Integer> paperPalette =
                inksOf(ChartPalette.WHITE_PAPER);
        int paperGround = ChartPalette.WHITE_PAPER.ground().getRGB();
        paperPalette.add(paperGround);
        long classAgree = 0;
        long maskAgree = 0;
        int maskDiffer = 0;
        for (int y = 0; y < black.getHeight(); y++) {
            for (int x = 0; x < black.getWidth(); x++) {
                int onPaper = classify(paper.getRGB(x, y),
                        paperGround, paperPalette);
                int onBlack = classify(black.getRGB(x, y), ground,
                        palette);
                if (onPaper == onBlack) {
                    classAgree++;
                }
                if ((onPaper == 0) == (onBlack == 0)) {
                    maskAgree++;
                } else {
                    maskDiffer++;
                }
            }
        }
        System.out.printf(Locale.ROOT,
                "| %s | %s | %.2f%% | %d (%.3f%%) | %d | %.3f%% |"
                        + " %.3f%% | %d |%n",
                page.name(), page.why(),
                100.0 * palettePixels / total, aaPixels,
                100.0 * aaPixels / total, aaGreys,
                100.0 * classAgree / total, 100.0 * maskAgree / total,
                maskDiffer);

        if (page.name().equals("m31-08")) {
            int fill = ChartPalette.BLACK_SKY.galaxyFill().getRGB();
            int fillPixels = census.getOrDefault(fill, 0);
            if (fillPixels == 0) {
                throw new IllegalStateException("the galaxy fill is"
                        + " invisible on the black reference page -"
                        + " the whisper has gone silent");
            }
            System.out.printf(Locale.ROOT,
                    "%n`m31-08-black`: the galaxy fill is present"
                            + " and itself - %d pixels of exact grey"
                            + " %d inside M31's ellipse.%n%n",
                    fillPixels, fill & 0xff);
        }
        if (page.key()) {
            furniture(page, black, ground);
        }
    }

    /**
     * Furniture interiors are the ground, not white islands: one
     * probe just inside each block's border, in the padding no text
     * reaches.
     */
    private static void furniture(Page page, BufferedImage black,
                                  int ground) {
        int corner = black.getRGB(3, 3);
        // The title block sits at the lower left with a 12 px margin
        // and 8 px padding; 3 px inside its border is padding.
        int titleProbe = black.getRGB(12 + 3,
                black.getHeight() - 12 - 3);
        if (titleProbe != ground) {
            throw new IllegalStateException(page.name() + ": the"
                    + " title block's interior is not the ground:"
                    + " grey " + (titleProbe & 0xff));
        }
        System.out.printf(Locale.ROOT, "`%s-black`: furniture"
                + " interiors are the ground (title-block padding"
                + " probe grey %d, page corner grey %d) - opaque"
                + " blocks, no white islands.%n%n",
                page.name(), titleProbe & 0xff, corner & 0xff);
    }

