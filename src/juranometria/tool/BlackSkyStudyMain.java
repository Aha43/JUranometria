    private static void constancies() {
        System.out.println("## What stays constant, and where it is"
                + " proven");
        System.out.println();
        System.out.println("- **The white-paper chart is"
                + " byte-identical.** `ChartOptions.DEFAULTS` carries"
                + " white paper, every released reference comparison"
                + " and ink-count test runs through it unchanged, and"
                + " the palette reaches rendering only through the"
                + " options value.");
        System.out.println("- **The application theme never reaches"
                + " chart ink.** The palette lives in"
                + " `ChartPalette`, consulted only by the chart's"
                + " own painters; the renderer reads nothing from"
                + " `UIManager`, and the both-themes byte-identity"
                + " tests now run the black page too.");
        System.out.println("- **Enlarged application text does not"
                + " reach the page.** Chart label faces are the"
                + " renderer's own fixed fonts, not the"
                + " application's `defaultFont`; the dialog and its"
                + " Black sky control follow application text size"
                + " like every other control.");
        System.out.println("- **Switching is repaint-only.** The"
                + " palette is a `ChartOptions` component, invisible"
                + " to scene assembly by construction; the scene,"
                + " inventory, catalogue-query count, centre, field,"
                + " limit, target, selection, and working marks are"
                + " untouched, asserted by the journey tests.");
        System.out.println("- **Modules stay colour-free.** They"
                + " contribute typed geometry and ink roles; the"
                + " chart's two ink painters translate role to"
                + " palette colour.");
        System.out.println();
        System.out.println("## The Milky Way, deferred");
        System.out.println();
        System.out.println("`ChartPalette` deliberately carries no"
                + " Milky Way colour: that imagery is parked"
                + " unlicensed (Sprint 22), and choosing its"
                + " dark-ground treatment before the source is"
                + " licensed would be a palette chosen in advance of"
                + " its data. The compatibility question is recorded"
                + " in docs/decisions/black-sky.md, not answered"
                + " here.");
    }
