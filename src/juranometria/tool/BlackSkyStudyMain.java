/**
 * The black-sky design study (Sprint 26, issue #246): the second
 * intentional chart palette, derived from measurement rather than
 * inverted mechanically.
 *
 * <p>Prints the measurements to stdout (the Makefile writes them to
 * the committed study document) and renders the representative pages
 * beside them, through the production renderer, in both palettes.
 * The derivation rule is executed here against the white-paper
 * palette and compared with what {@link ChartPalette#BLACK_SKY}
 * pins - the verify-icons pattern: is what we ship still what the
 * rule derives? A mismatch fails the run.
 *
 * <p>Fails loudly on any pixel breach: a bulk colour outside the
 * reviewed palette, a non-grey pixel, an invisible galaxy fill, or
 * furniture whose interior is not the ground.
 */
