package juranometria.tool;

import java.io.IOException;

import juranometria.solar.SaturnSystemService;

/**
 * The Saturn service's accuracy against JPL Horizons and the named
 * cases, as a kept report (issue #575): every quantity's worst
 * difference by body and era over the committed fixtures, the ring
 * openings on Horizons' planetodetic reading, every state disagreement
 * and every flattened-against-sphere row named, the ring-plane
 * crossings (validated only against Horizons), Titan's greatest
 * elongations and IMCCE's quoted events. Deterministic: the service
 * and the fixtures are fixed, the numbers are rounded. Written to
 * {@code docs/studies/saturn-system/service-accuracy.md} by
 * {@code make saturn-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class SaturnAccuracyReportMain {

    private SaturnAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        SaturnSystemService service = SaturnSystemService.load();
        SaturnComparison.Result result = new SaturnComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Saturn service against Horizons and the named cases (#575)\n\n")
                .append("Generated by `juranometria.tool.SaturnAccuracyReportMain`")
                .append(" (`make saturn-accuracy-report`) from the service over the bundled packs,")
                .append(" the Horizons responses kept under `horizons/` and IMCCE's rows quoted in")
                .append(" `imcce-quoted-rows.txt`; `SaturnReferenceVectorTest` holds these numbers to")
                .append(" the targets ruled on #574. Observers at sea level, UT1 = UTC, the Sun's")
                .append(" gravitational deflection in every apparent place, the flattened IAU 2015")
                .append(" figure for the reader's disc and shadow and Horizons' equatorial sphere for")
                .append(" the comparison's. The moons answer from ").append(service.pack().moonsFirstDay())
                .append("; Saturn from ").append(service.pack().saturnFirstDay())
                .append("; the exact-time interval ends ").append(service.timeScales().exactUntil())
                .append(".\n\n")
                .append(SaturnComparison.report(result));
        System.out.print(out);
    }
}
