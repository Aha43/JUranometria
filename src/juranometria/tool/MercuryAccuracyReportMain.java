package juranometria.tool;

import java.io.IOException;

import juranometria.solar.MercuryService;

/**
 * The Mercury service's accuracy against JPL Horizons and Espenak's named
 * events, as a kept report (issue #529): every quantity's worst
 * difference by era beside the target ruled on #528, the side of the
 * Sun on every row, χ against Horizons' own Sun and Mercury, and the
 * published conjunctions and greatest elongations. Deterministic: the
 * service and the fixtures are fixed, the numbers are rounded. Written
 * to {@code docs/studies/mercury/service-accuracy.md} by
 * {@code make mercury-accuracy-report}; the tests hold the same engine's
 * results to the ruled targets.
 */
public final class MercuryAccuracyReportMain {

    private MercuryAccuracyReportMain() {
    }

    public static void main(String[] args) throws IOException {
        MercuryService service = MercuryService.load();
        MercuryComparison.Result result = new MercuryComparison(service).run();
        StringBuilder out = new StringBuilder();
        out.append("# The Mercury service against Horizons and Espenak (#529)\n\n")
                .append("Generated by `juranometria.tool.MercuryAccuracyReportMain`")
                .append(" (`make mercury-accuracy-report`) from the service over the")
                .append(" bundled Solar System and planets packs and the Horizons responses")
                .append(" committed under `horizons/`; `MercuryReferenceVectorTest` and")
                .append(" `MercuryNamedEventsTest` hold these numbers to the targets ruled on")
                .append(" #528. Observers at sea level, UT1 = UTC, the atlas's own time scales,")
                .append(" the Sun's gravitational deflection in every apparent place, the")
                .append(" Moon's S-T-O phase angle, the PCK's equatorial radius. Mercury answers from ")
                .append(service.firstDay()).append(" to ").append(service.lastDay())
                .append(".\n\n")
                .append(MercuryComparison.report(result));
        System.out.print(out);
    }
}
