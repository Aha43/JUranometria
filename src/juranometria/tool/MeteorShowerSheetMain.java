/**
 * Every word the meteor-shower panel says (#716, photographed for #718):
 * the one panel that <em>Solar System &gt; Meteor showers...</em> and the
 * Controller's group both show, over the bundled pack and the production
 * Sun and Moon, at stated chart times from Oslo - with no shower chosen,
 * with the Perseids active on the night of their nominal maximum, a week
 * later with that maximum passed, and in December with the shower not
 * active. Both interface languages, on both grounds, drawn on a fixed
 * canvas at the dialog's stated width and at the panel's own preferred
 * width - the narrowest the Controller draws it - and every visible,
 * spoken and explained word in {@code meteor-strings.md}. The two
 * actions are wired as the application wires them, to a chart context
 * and a centring that the photograph never uses.
 *
 * <p>No window is opened: the panel is one component in two hosts, and
 * what a host adds is a title and a size.
 */
public final class MeteorShowerSheetMain {

    /** What this photographer holds still: a fixed canvas per surface. */
    public static final SheetCapture.Kind CAPTURE_KIND = SheetCapture.Kind.FIXED_CANVAS;

    private static Path out = Path.of("docs/studies/interface-language");

    /** The width the dialog states for itself ({@code MeteorShowerDialog}). */
    private static final int DIALOG_WIDTH = 560;
    /**
     * The panel's own preferred width: the narrowest the Controller ever
     * draws it, because the Controller is never narrower than its widest
     * tab asks ({@code CompanionWindow.updateMinimum}).
     */
    private static final int PREFERRED_WIDTH = -1;

    private static final Instant MAXIMUM_NIGHT = Instant.parse("2027-08-13T00:00:00Z");
    private static final Instant A_WEEK_LATER = Instant.parse("2027-08-20T00:00:00Z");
    private static final Instant DECEMBER = Instant.parse("2027-12-14T20:00:00Z");

    private static MeteorShowers showers;
    private static SolarSystemService solar;

    private MeteorShowerSheetMain() {
    }

    public static void main(String[] args) throws Exception {
        if (args.length > 0 && !args[0].isBlank()) {
            out = Path.of(args[0]);
        }
        Files.createDirectories(out);
        // The look and feel is put back when the sheets are drawn, so this
        // photographer leaves the process as it found it.
        javax.swing.LookAndFeel before = javax.swing.UIManager.getLookAndFeel();
        boolean hadFont = javax.swing.UIManager.getDefaults().containsKey("defaultFont");
        Object font = hadFont ? javax.swing.UIManager.get("defaultFont") : null;
        try {
            sheets();
        } finally {
            SwingUtilities.invokeAndWait(() -> {
                javax.swing.UIManager.put("defaultFont", font);
                try {
                    javax.swing.UIManager.setLookAndFeel(before);
                } catch (javax.swing.UnsupportedLookAndFeelException gone) {
                    throw new IllegalStateException(gone);
                }
            });
        }
    }

    private static void sheets() throws Exception {
        solar = SolarSystemService.load();
        showers = new MeteorShowers(MeteorShowerPack.load(), solar::solarLongitudeJ2000Degrees);
        StringBuilder said = new StringBuilder("""
                # Every word the meteor-shower panel says

                Issue #716 (meteor showers at chart time, ruled on #715);
                photographed for the 6.6.0 handover, #718. Generated by
                `juranometria.tool.MeteorShowerSheetMain` from compiled
                application classes and their classpath resources: the one
                panel that *Solar System > Meteor showers...* and the
                Controller's *Meteor showers* group both show, over the
                bundled pack and the production Sun and Moon, from Oslo
                (59.91° N, 10.75° E) at stated chart times. Each state in
                both interface languages; the active state on both grounds,
                and at the panel's own preferred width, which is the
                narrowest the Controller ever draws it.

                Source: International Meteor Organization (IMO) – www.imo.net.
                The values are nominal, from the edition the panel names.

                **Norsk bokmål — reviewed in use, not from this page.** The
                Norwegian terms were ruled by the owner on #715 (C-7), the
                panel was read in the owner's hands at the #716 checkpoint
                of 2026-11-14, and the month names were corrected at the
                #717 text checkpoint of 2026-11-15. This page itself was
                generated afterwards.

                """);
        for (String language : List.of("en", "nb-NO")) {
            InterfaceText words = InterfaceText.forLanguage(language);
            said.append("## ").append(language.equals("en") ? "English" : "Norsk bokmål")
                    .append(" (`").append(language).append("`)\n\n");
            said.append("| the host | words |\n|---|---|\n")
                    .append("| the dialog's title | ").append(cell(words.say("meteor.title")))
                    .append(" |\n| the dialog, explained | ")
                    .append(cell(words.say("meteor.explain"))).append(" |\n\n");

            said.append(describe("No shower chosen, chart time 2027-08-13 00:00 UTC",
                    draw(words, false, null, MAXIMUM_NIGHT, DIALOG_WIDTH,
                            out.resolve("meteor-" + language + "-1-none-light.png"))));
            said.append(describe("The Perseids, active, on the night of their nominal maximum",
                    draw(words, false, "PER", MAXIMUM_NIGHT, DIALOG_WIDTH,
                            out.resolve("meteor-" + language + "-2-active-light.png"))));
            draw(words, true, "PER", MAXIMUM_NIGHT, DIALOG_WIDTH,
                    out.resolve("meteor-" + language + "-3-active-dark.png"));
            said.append(describe("The Perseids a week later, their maximum passed",
                    draw(words, false, "PER", A_WEEK_LATER, DIALOG_WIDTH,
                            out.resolve("meteor-" + language + "-4-passed-light.png"))));
            said.append(describe("The Perseids in December, not active",
                    draw(words, false, "PER", DECEMBER, DIALOG_WIDTH,
                            out.resolve("meteor-" + language + "-5-not-active-light.png"))));
            draw(words, false, "PER", MAXIMUM_NIGHT, PREFERRED_WIDTH,
                    out.resolve("meteor-" + language + "-6-narrowest-light.png"));
            draw(words, true, "PER", MAXIMUM_NIGHT, PREFERRED_WIDTH,
                    out.resolve("meteor-" + language + "-7-narrowest-dark.png"));
            said.append("The dark ground (`-3-active-dark`) and the narrowest width"
                    + " (`-6-narrowest-light`, `-7-narrowest-dark`) show the active"
                    + " state's words above, unchanged.\n\n");
        }
        Files.writeString(out.resolve("meteor-strings.md"), said.toString(),
                StandardCharsets.UTF_8);
        System.out.println("meteor-shower sheets: " + out.resolve("meteor-strings.md"));
    }

    /** The panel over a session of its own, read once, as a host shows it. */
    private static MeteorShowerControls panel(InterfaceText words, String code, Instant when) {
        MeridianModule placeAndTime = new MeridianModule(new Observer(59.91, 10.75, when));
        MeteorShowerModule module = new MeteorShowerModule(placeAndTime::observer,
                () -> showers, () -> false);
        MeteorShowerSession session = new MeteorShowerSession(placeAndTime::observer,
                () -> showers, () -> solar, module);
        session.installThrough(placeAndTime.context());
        session.centreThrough(position -> { });
        if (code != null) {
            session.select(code);
        }
        MeteorShowerControls controls = new MeteorShowerControls(session, words);
        controls.refresh();
        return controls;
    }

    private static MeteorShowerControls draw(InterfaceText words, boolean dark, String code,
                                             Instant when, int asked, Path to) throws Exception {
        MeteorShowerControls[] made = new MeteorShowerControls[1];
        Color[] ground = new Color[1];
        SwingUtilities.invokeAndWait(() -> {
            juranometria.app.UiTheme.apply(dark);
            made[0] = panel(words, code, when);
            ground[0] = javax.swing.UIManager.getColor("Panel.background");
        });
        MeteorShowerControls content = made[0];
        int width = asked == PREFERRED_WIDTH ? content.getPreferredSize().width : asked;
        if (asked == PREFERRED_WIDTH) {
            System.out.println("preferred width " + width + " px: " + to.getFileName());
        }
        BufferedImage sheet = SheetCapture.take(content,
                SheetCapture.fixedCanvas(() -> {
                    content.setSize(width, content.getPreferredSize().height);
                    layoutDeeply(content);
                    content.setSize(width, content.getPreferredSize().height);
                    layoutDeeply(content);
                }),
                SheetCapture.Premise.none(),
                () -> {
                    BufferedImage drawn = new BufferedImage(width, content.getHeight(),
                            BufferedImage.TYPE_INT_RGB);
                    Graphics2D g = drawn.createGraphics();
                    try {
                        g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING,
                                RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
                        g.setColor(ground[0] == null ? Color.WHITE : ground[0]);
                        g.fillRect(0, 0, width, content.getHeight());
                        content.paint(g);
                    } finally {
                        g.dispose();
                    }
                    return drawn;
                });
        ImageIO.write(sheet, "png", to.toFile());
        SwingUtilities.invokeAndWait(content::release);
        return content;
    }

    private static void layoutDeeply(Container from) {
        from.doLayout();
        for (Component child : from.getComponents()) {
            if (child instanceof Container nested) {
                layoutDeeply(nested);
            }
        }
    }

    private static String describe(String surface, JComponent content) {
        StringBuilder rows = new StringBuilder("### ").append(surface).append("\n\n")
                .append("| kind | shown | spoken as | explained as |\n|---|---|---|---|\n");
        for (Component control : reading(content)) {
            if (control.getParent() instanceof JComboBox<?>) {
                continue; // the selector's own arrow and editor, not controls of the panel
            }
            String kind;
            String shown;
            if (control instanceof JLabel label) {
                kind = "label";
                shown = label.getText();
            } else if (control instanceof AbstractButton button) {
                kind = button.isEnabled() ? "button" : "button, unavailable";
                shown = button.getText();
            } else if (control instanceof JComboBox<?> box) {
                kind = "selector";
                List<String> items = new ArrayList<>();
                for (int i = 0; i < box.getItemCount(); i++) {
                    String item = String.valueOf(box.getItemAt(i));
                    items.add(i == box.getSelectedIndex() ? "**" + item + "**" : item);
                }
                shown = String.join(" · ", items);
            } else if (control instanceof JTextArea area) {
                kind = "text";
                shown = area.getText();
            } else {
                continue;
            }
            JComponent spoken = (JComponent) control;
            if ((shown == null || shown.isBlank())
                    && spoken.getAccessibleContext().getAccessibleName() == null) {
                continue;
            }
            rows.append("| ").append(kind)
                    .append(" | ").append(cell(shown))
                    .append(" | ").append(cell(spoken.getAccessibleContext().getAccessibleName()))
                    .append(" | ").append(cell(
                            spoken.getAccessibleContext().getAccessibleDescription()))
                    .append(" |\n");
        }
        return rows.append('\n').toString();
    }

    private static String cell(String text) {
        return text == null || text.isBlank() ? "—"
                : text.replace("|", "\\|").replace("\n", " / ");
    }

    private static List<Component> reading(Container from) {
        List<Component> found = new ArrayList<>();
        for (Component child : from.getComponents()) {
            if (!child.isVisible()) {
                continue;
            }
            found.add(child);
            if (child instanceof Container nested) {
                found.addAll(reading(nested));
            }
        }
        return found;
    }
}
